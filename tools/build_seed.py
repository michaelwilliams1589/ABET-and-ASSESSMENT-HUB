"""Builds assets/historical-seed.js and assets/assessment-schedule-data.js from the
ABET spreadsheets. Run:  python3 tools/build_seed.py /path/to/abet/files
Only program-level counts are written (no student names or IDs)."""
import json, re, sys, openpyxl, os
src = sys.argv[1] if len(sys.argv) > 1 else "../files"
out = os.path.join(os.path.dirname(__file__), "..", "assets")

# ---- Assessment schedule (2023-24 .. 2025-26) ----
ws = openpyxl.load_workbook(os.path.join(src, "ABET Assessment Schedule.xlsx"), data_only=True).active
cols = {"L": ("2023-24", "Fall"), "M": ("2023-24", "Spring"), "N": ("2023-24", "Summer"),
        "P": ("2024-25", "Fall"), "Q": ("2024-25", "Spring"), "R": ("2024-25", "Summer"),
        "S": ("2025-26", "Fall"), "T": ("2025-26", "Spring"), "U": ("2025-26", "Summer")}
schedule, so = [], 0
for row in ws.iter_rows(min_row=5):
    a = row[0].value
    if not a: continue
    a = str(a).strip()
    if a.lower().startswith("an ability"): so += 1; continue
    if a.lower().startswith("legend"): break
    m = re.match(r"(ETD[EG]?)\s*(\d{4})\s*(.*)", a)
    instr = ws[f"O{row[0].row}"].value
    for c, (ay, term) in cols.items():
        v = ws[f"{c}{row[0].row}"].value
        if v and str(v).strip().upper() == "A":
            schedule.append({"so": f"SO{so}", "academicYear": ay, "term": term,
                             "courseCode": f"{m.group(1)} {m.group(2)}" if m else a,
                             "tool": (m.group(3) if m else a).strip(), "instructor": instr or ""})
with open(os.path.join(out, "assessment-schedule-data.js"), "w") as f:
    f.write("// Generated by tools/build_seed.py from 'ABET Assessment Schedule.xlsx'. (A)ssess entries only.\n")
    f.write("window.ETDE_ASSESSMENT_SCHEDULE=" + json.dumps(schedule, indent=1) + ";\n")

# ---- Historical results (counts only) ----
seed = []
def add(**k): seed.append(k)
# Capstone Grade Sheet Fall 2024 copy: Spring 2023 summary table (row 2 = outcomes, row 4 = assessed, row 5 = successful)
def num(v):
    try: return int(float(v))
    except (TypeError, ValueError): return None
ws = openpyxl.load_workbook(os.path.join(src, "Copy of Assessment Results (Capstone Grade Sheet Fall 2024).xlsx"), data_only=True)["Sheet1"]
heads = [c.value for c in ws[2]]; n = [c.value for c in ws[4]]; s = [c.value for c in ws[5]]
course_for = {"SO 3": ("ETDE 4813", "Capstone presentation rubric Q1"), "SO 1": ("ETDE 2223", "Power Distribution Lab 1 single-phase power"),
              "SO 2": ("ETDE 3143", "Lab 1 Parking Garage HMI (bar graph labels it Intro to PLC)"), "SO 4": ("ETDE 1283", "Circuits I Lab 5 Ohm's Law")}
for i, h in enumerate(heads):
    if not h: continue
    key = re.match(r"SO \d", str(h)).group(0)
    if num(n[i]) is not None and num(s[i]) is not None:
        cc, tool = course_for[key]
        add(so=key.replace(" ", ""), academicYear="2022-23", term="Spring 2023", courseCode=cc, tool=tool,
            assessed=num(n[i]), met=num(s[i]), source="Copy of Assessment Results (Capstone Grade Sheet Fall 2024).xlsx / Sheet1", note="")
# SO 5
ws = openpyxl.load_workbook(os.path.join(src, "Student Outcome 5 Data.xlsx"), data_only=True)["Student Outcome 5"]
terms = {"ETDE 1373": ("Fall 2025", "Final Arduino project"), "ETDE 4112": ("Fall 2025", "Employer evaluation"), "ETDE 4813": ("Spring 2026", "Group and individual leadership/teamwork")}
for col in "BCD":
    cc = re.search(r"ETDE \d{4}", ws[f"{col}3"].value).group(0)
    add(so="SO5", academicYear="2025-26", term=terms[cc][0], courseCode=cc, tool=terms[cc][1],
        assessed=int(ws[f"{col}4"].value), met=int(ws[f"{col}5"].value),
        source="Student Outcome 5 Data.xlsx / Student Outcome 5", note="Term taken from the assessment schedule (the workbook has no date).")
# SO 3 (workbook has student totals but the pass counts were never filled in)
ws = openpyxl.load_workbook(os.path.join(src, "SO 3 Data.xlsx"), data_only=True)["SO 3 Bar Graph (2)"]
sched_term = {x["courseCode"]: f'{x["term"]} {"2024" if x["term"]=="Fall" else "2025"}' for x in schedule if x["so"] == "SO3"}
for r in range(3, 10):
    label = str(ws[f"H{r}"].value)
    cc = re.search(r"ETDE \d{4}", label).group(0); tot = int(re.search(r"(\d+)\s*Total", label, re.I).group(1))
    add(so="SO3", academicYear="2024-25", term=sched_term.get(cc, ""), courseCode=cc, tool=label.split("\n")[0].strip(),
        assessed=tot, met=None, source="SO 3 Data.xlsx / SO 3 Bar Graph (2)",
        note="Number of successful students is blank in the workbook. Enter it after import.")
with open(os.path.join(out, "historical-seed.js"), "w") as f:
    f.write("// Generated by tools/build_seed.py. Program-level counts only; no student names or IDs.\n")
    f.write("window.ETDE_HISTORICAL_SEED=" + json.dumps(seed, indent=1) + ";\n")
print(len(schedule), "schedule rows;", len(seed), "historical rows")

# ---- PEO x SO map: how many course objectives link each PEO to each SO ----
ws = openpyxl.load_workbook(os.path.join(src, "All_Courses_PEO_SO_Mapping_Summary.xlsx"), data_only=True)["Detailed Mapping"]
matrix = {}
for row in ws.iter_rows(min_row=2, values_only=True):
    vals = [v for v in row]
    peos = re.findall(r"PEO\s*\d", " ".join(str(v) for v in vals if v)); sos = re.findall(r"SO\s*\d", " ".join(str(v) for v in vals[-1:] if v))
    for p_ in set(x.replace(" ", "") for x in peos):
        for so_ in set(x.replace(" ", "") for x in sos):
            matrix.setdefault(p_, {}).setdefault(so_, 0); matrix[p_][so_] += 1
with open(os.path.join(out, "historical-seed.js"), "a") as f:
    f.write("// PEO-to-SO links counted from All_Courses_PEO_SO_Mapping_Summary.xlsx (Detailed Mapping).\n")
    f.write("window.ETDE_PEO_SO_SEED=" + json.dumps(matrix, sort_keys=True) + ";\n")
print("PEO map:", matrix)
